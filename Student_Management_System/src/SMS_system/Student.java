package SMS_system;


public class Student {
	private String name;
	private int age;
	public Student() {
		

	}
	public void setage(int age) {
		this.age = age;
	}
	public void setname(String name) {
		this.name = name;
	}
	
	public int getage() {
		return age;
	}
	public String getname() {
		return name;
	}
	

}
